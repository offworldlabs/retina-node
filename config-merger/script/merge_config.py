#!/usr/bin/env python3
"""
Config merge script for blah2 and tar1090-node

Designed to be run in both blah2 and blah2-api containers with baked-in configs.
Merges default.yml + user.yml + forced.yml into config.yml.
Also syncs the node_id field in user.yml from Mender device identity (/data/mender/node_id).
Generates tar1090.env for tar1090-node if the tar1090 section exists in config.
Generates retina-tracker.yaml for the retina-tracker sidecar if the
retina_tracker section exists in config.

Takes as inputs:
1. Defaults directory - holds baked-in default.yml and forced.yml
2. User config path - the path to the shared persistent directory (in the /data partition)
   where the user config overlay, user.yml. If this does not exist, it is created by copying defaults.yml.
3. Output config path - the output location of the generated merged config file,
   should live separately in each container to avoid race conditions

Merge order (later overrides earlier):
  default.yml -> user.yml -> forced.yml

Outputs:
  - config.yml: Merged configuration for blah2
  - tar1090.env: Environment variables for tar1090-node
  - retina-tracker.yaml: Config overrides for the retina-tracker sidecar
"""

import os
import sys

import yaml
from mergedeep import merge

# The Doppler span default.yml shipped up to and including v0.4.5.0. A user.yml
# holding exactly this pair is assumed to be the merger's own first-boot copy
# rather than anyone's choice. See migrate_doppler_span().
LEGACY_DOPPLER_MIN = -200
LEGACY_DOPPLER_MAX = 200

# The tracker_forward block default.yml shipped while retina-gui still did the
# forwarding itself. A user.yml holding exactly this is the merger's own
# first-boot copy rather than anyone's choice. See migrate_tracker_forward().
LEGACY_TRACKER_FORWARD = {
    'enabled': False,
    'host': 'blah2_tracker',
    'port': 3012,
}

# The ADS-B truth server default.yml shipped before the truth feed was pointed at
# the node's own tar1090. A user.yml holding exactly this is the merger's own
# first-boot copy rather than anyone's choice. See migrate_adsb_truth_server().
LEGACY_ADSB_TAR1090 = 'sfo1.retnode.com'


def get_node_id_from_mender():
    """Read node_id from Mender device identity file (generated by mender-device-identity)"""
    node_id_file = '/data/mender/node_id'
    try:
        with open(node_id_file) as f:
            node_id = f.read().strip()
            if node_id:
                return node_id
    except FileNotFoundError:
        print(f"Mender node_id file not found: {node_id_file}")
    except Exception as e:
        print(f"Could not read node_id from {node_id_file}: {e}")

    return None


MENDER_COMPOSE_ROOT = '/data/mender-docker-compose'


def write_file_atomic(path, content):
    """Replace path with content so that a power cut leaves the old file or the
    new one, never a mix.

    A plain rewrite in place can leave the file at its new length with its data
    never written, which ext4 on an SD card reads back as NUL bytes. A NUL-filled
    manifests/.env stops compose parsing the project at all, including the
    `run config-merger` that would regenerate it, so a node that loses power at
    the wrong moment cannot recover by itself. The fsyncs put the data on disk
    before the rename is committed, and the rename itself on disk before return.
    """
    temp_path = path + '.tmp.' + str(os.getpid())
    with open(temp_path, 'w') as f:
        f.write(content)
        f.flush()
        os.fsync(f.fileno())
    os.replace(temp_path, path)
    dir_fd = os.open(os.path.dirname(path) or '.', os.O_RDONLY)
    try:
        os.fsync(dir_fd)
    finally:
        os.close(dir_fd)


def generate_env_file(config, output_dir):
    """Generate .env file for ADS-B services (readsb, tar1090) from merged config"""
    if 'tar1090' not in config:
        print("No tar1090 config found, skipping .env generation")
        return

    tar1090_config = config['tar1090']
    # Use tar1090.location if set, otherwise fall back to location.rx (receiver location)
    location = tar1090_config.get('location') or (config.get('location') or {}).get('rx') or {}

    env_path = os.path.join(output_dir, 'tar1090.env')
    print(f"Writing tar1090 .env to {env_path}")

    lat = location.get('latitude')
    lon = location.get('longitude')
    alt = location.get('altitude')
    sited = lat is not None and lon is not None

    lines = ["# Auto-generated by config-merger - do not edit manually\n\n"]

    # Receiver location (matches tar1090-node .env.example format).
    # Omitted when unset. This used to default to 0, which is Null Island:
    # a real place the node then claimed to be.
    lines.append("# Receiver location\n")
    if sited:
        lines.append(f"RECEIVER_LAT={lat}\n")
        lines.append(f"RECEIVER_LON={lon}\n")
        lines.append(f"RECEIVER_ALT={alt if alt is not None else 0}\n\n")
    else:
        lines.append("# unset: no receiver location has been configured\n\n")

    # adsb.lol integration. Forced off without a location whatever the
    # config says: the query is a radius around the receiver, so with no
    # receiver there is no query to make, only a wrong one.
    adsblol = bool(tar1090_config.get('adsblol_fallback', False)) and sited
    lines.append("# adsb.lol integration\n")
    lines.append(f"ADSBLOL_ENABLED={'true' if adsblol else 'false'}\n")
    lines.append(f"ADSBLOL_RADIUS={tar1090_config.get('adsblol_radius', 40)}\n\n")

    # External ADS-B feed for readsb
    adsb_source = tar1090_config.get('adsb_source', '')
    if adsb_source:
        lines.append("# readsb external feed\n")
        lines.append(f"READSB_NET_CONNECTOR={adsb_source}\n")

    content = ''.join(lines)
    write_file_atomic(env_path, content)
    print("tar1090 .env generated successfully!")

    # Copy .env to Mender compose directories for variable substitution
    # mender-docker-compose uses current/ (active) and new/ (staging during update)
    for slot in ['current', 'new']:
        manifests_dir = os.path.join(MENDER_COMPOSE_ROOT, slot, 'manifests')
        env_dest = os.path.join(manifests_dir, '.env')
        try:
            if os.path.isdir(manifests_dir):
                write_file_atomic(env_dest, content)
                print(f"Copied .env to {env_dest}")
        except Exception as e:
            print(f"Note: Could not copy to {env_dest}: {e}")


def generate_retina_tracker_config(config, output_dir):
    """Generate a config file for the retina-tracker sidecar from the merged
    config's `retina_tracker` section.

    retina_tracker.config.load_config() shallow-merges this per top-level
    section (`default_config[key].update(loaded[key])`), so only the
    overridden keys need to be present here - everything else falls back to
    the package's own built-in defaults. All fields under `retina_tracker`
    here are assumed to belong to retina-tracker's own `tracker` section;
    revisit this mapping if fields for its other sections (`process_noise`,
    `tracklet`, `adsb`, ...) are ever added to default.yml.
    """
    if 'retina_tracker' not in config:
        print("No retina_tracker config found, skipping retina-tracker.yaml generation")
        return

    output_path = os.path.join(output_dir, 'retina-tracker.yaml')
    print(f"Writing retina-tracker config to {output_path}")

    write_file_atomic(output_path, yaml.dump(
        {'tracker': config['retina_tracker']}, default_flow_style=False, sort_keys=False))
    print("retina-tracker.yaml generated successfully!")


def migrate_gain_reduction(config):
    """Convert legacy scalar gainReduction (pre-per-tuner) to [reference, surveillance] pair.

    Older user.yml overlays persisted on devices may still carry a single scalar value
    for capture.device.gainReduction, which would otherwise clobber the new default.yml's
    list value during merge and break blah2's per-tuner RSPduo gain support.
    """
    try:
        gain = config['capture']['device']['gainReduction']
    except (KeyError, TypeError):
        return

    if isinstance(gain, (int, float)):
        print(f"Migrating legacy scalar gainReduction ({gain}) to per-tuner pair [{gain}, {gain}]")
        config['capture']['device']['gainReduction'] = [gain, gain]


def migrate_doppler_span(user):
    """Drop a Doppler span the user never chose, so default.yml can change it.

    On first boot the merger seeds user.yml with a whole copy of default.yml, so
    every deployed node persists the shipped Doppler span whether or not anyone
    selected it. Without this, a change to default.yml could never reach a node
    that has already booted once.

    Only the exact legacy pair is dropped, and only when both bounds match: any
    other value is a deliberate setting and is left alone. owl runs +/-1000 Hz,
    which must survive. A node that genuinely wants +/-200 Hz is indistinguishable
    from a first-boot copy, so it moves to the new default and has to be set
    again if that is not wanted.

    Dropping the keys rather than rewriting them means whatever default.yml ships
    takes effect, including a later change to some other value. user.yml on disk
    is untouched, so this stays load-bearing: remove it and nodes fall back to
    the +/-200 Hz their overlay still holds.
    """
    try:
        ambiguity = user['process']['ambiguity']
    except (KeyError, TypeError):
        return

    if not isinstance(ambiguity, dict):
        return

    if (ambiguity.get('dopplerMin') == LEGACY_DOPPLER_MIN
            and ambiguity.get('dopplerMax') == LEGACY_DOPPLER_MAX):
        print(f"Dropping first-boot Doppler span ({LEGACY_DOPPLER_MIN}/{LEGACY_DOPPLER_MAX} Hz) "
              "from user config so the shipped default applies")
        del ambiguity['dopplerMin']
        del ambiguity['dopplerMax']


def migrate_tracker_forward(user):
    """Drop a tracker_forward the user never chose, so default.yml can change it.

    Detections reach the tracker one way or the other: retina-gui used to forward
    them, and now blah2-api does, over the socket named here. The handover has to
    happen on every node at once, because the tracker's ingest accepts a single
    connection and whichever producer holds it locks the other out.

    The first-boot copy problem is the same one migrate_doppler_span() solves: the
    merger seeds user.yml from default.yml, so every node already on the estate
    persists the block that shipped when it booted, and a change to default.yml
    could never reach it.

    Narrower than the Doppler case, because the legacy value is not something a
    node could sensibly be set to. 'blah2_tracker' is a compose service name, and
    these nodes run blah2-api with network_mode host where it resolves to nothing,
    so a node deliberately pointed there is already not forwarding. Only the whole
    legacy triple matches: a node aimed at some other host or port is a real
    choice and is left alone.

    Dropping the keys rather than rewriting them means whatever default.yml ships
    applies, including a later change of host or port. user.yml on disk is
    untouched, so this stays load-bearing rather than a one-shot fixup.
    """
    try:
        network = user['network']
    except (KeyError, TypeError):
        return

    if not isinstance(network, dict):
        return

    if network.get('tracker_forward') == LEGACY_TRACKER_FORWARD:
        print("Dropping first-boot tracker_forward (disabled, blah2_tracker:3012) "
              "from user config so the shipped default applies")
        del network['tracker_forward']


def migrate_remove_tracker(user):
    """Drop blah2's built-in tracker settings, which no longer exist.

    blah2's own tracker was removed outright: nothing consumed it (retina-gui's
    Tracker page reads the retina-tracker sidecar, and blah2-api's /api/tracker
    is gone with it), and it carried an unbounded leak - Track::remove() never
    erased nInactive, which Tracker::process() then deep copied every CPI, worth
    roughly 3 MB/h on a board with no swap.

    default.yml no longer ships these keys, but that alone reaches no node. The
    merger seeds user.yml with a whole copy of default.yml on first boot and
    user.yml overrides default.yml, so every node already on the estate persists
    the block that shipped when it booted. Same first-boot copy problem
    migrate_doppler_span() and migrate_tracker_forward() solve.

    Unconditional, unlike the migrations above, which compare against a LEGACY_*
    value so a deliberate choice survives. There is no deliberate choice to
    protect here: the code these keys configured does not exist, so any value is
    equally dead. network.ports.track goes the same way, since the socket blah2
    published tracks on and the listener blah2-api read them with are both gone.

    Dropping the keys rather than rewriting them leaves user.yml on disk
    untouched, so this stays load-bearing rather than a one-shot fixup, and a
    Mender rollback regenerates the old config from the old default.yml.

    Note for anyone bisecting: once this has run, a blah2 image from before the
    removal will abort on startup rather than warn, because it reads
    process.tracker.enable through ryml, whose default error handler calls
    abort(). Swap the config-merger image back at the same time.
    """
    try:
        process = user['process']
    except (KeyError, TypeError):
        process = None
    if isinstance(process, dict) and 'tracker' in process:
        print("Dropping first-boot process.tracker from user config: blah2's "
              "built-in tracker no longer exists")
        del process['tracker']

    try:
        ports = user['network']['ports']
    except (KeyError, TypeError):
        return
    if isinstance(ports, dict) and 'track' in ports:
        print("Dropping first-boot network.ports.track from user config: "
              "nothing publishes or listens on it any more")
        del ports['track']


def migrate_adsb_truth_server(user):
    """Drop an ADS-B truth server the user never chose, so default.yml can change it.

    The same first-boot copy problem as migrate_tracker_forward(): every node on
    the estate persists whatever truth server shipped when it booted, so changing
    default.yml alone reaches none of them.

    Narrow for the same reason that one is. 'sfo1.retnode.com' names a single
    machine that no second node has any reason to read its truth from, and it
    stopped answering: it returns HTTP 530 from every node and from off-estate,
    so a node still pointed there is getting no ADS-B at all and has nothing to
    lose. Any other value is a real choice and is left alone, including a
    receiver's own address, which is wrong in a different way this cannot judge.

    Dropping the key rather than rewriting it means whatever default.yml ships
    applies, including a later change of host or port. user.yml on disk is
    untouched, so this stays load-bearing rather than a one-shot fixup.
    """
    try:
        adsb = user['truth']['adsb']
    except (KeyError, TypeError):
        return

    if not isinstance(adsb, dict):
        return

    if adsb.get('tar1090') == LEGACY_ADSB_TAR1090:
        print(f"Dropping first-boot ADS-B truth server ({LEGACY_ADSB_TAR1090}) "
              "from user config so the shipped default applies")
        del adsb['tar1090']


def ensure_node_id(user_config_path):
    """Add/update node_id in user config from Mender device identity"""
    try:
        # Load current user config
        with open(user_config_path) as f:
            user_config = yaml.safe_load(f) or {}

        # Read node_id from Mender device identity (generated by mender-device-identity script)
        node_id = get_node_id_from_mender()
        if not node_id:
            print("No Mender node_id found, skipping node_id sync")
            return

        # Check if node_id already exists
        if 'network' in user_config and 'node_id' in user_config['network']:
            current_id = user_config['network']['node_id']
            if current_id == node_id:
                print(f"Node ID already correct: {node_id}")
                return
            else:
                # Node ID changed (board swap) - update it
                print(f"Node ID mismatch - updating from '{current_id}' to '{node_id}'")
        else:
            print(f"Syncing node_id from Mender identity: {node_id}")

        # Add/update node_id to network section
        if 'network' not in user_config:
            user_config['network'] = {}
        user_config['network']['node_id'] = node_id

        write_file_atomic(user_config_path, yaml.dump(
            user_config, default_flow_style=False, sort_keys=False))

        print(f"Node ID set in {user_config_path}")

    except Exception as e:
        print(f"Warning: Failed to ensure node_id: {e}")
        # Don't exit - continue with merge even if node_id fails


def main():
    # Parse command-line arguments
    if len(sys.argv) != 4:
        print("Usage: merge_config.py <defaults_dir> <user_config_path> <output_config_path>")
        print("Example: merge_config.py /config/defaults /data/retina-node/config/user.yml /data/retina-node/config/config.yml")
        sys.exit(1)

    defaults_dir = sys.argv[1]
    user_config_path = sys.argv[2]
    output_config_path = sys.argv[3]

    # Construct paths
    default_config = os.path.join(defaults_dir, 'default.yml')
    forced_config = os.path.join(defaults_dir, 'forced.yml')

    try:
        # Load default config (baked into container)
        print(f"Loading default config from {default_config}")
        with open(default_config) as f:
            config = yaml.safe_load(f)

        if not config:
            print("ERROR: Default config is empty or invalid")
            sys.exit(1)

        # Create user config from defaults if it doesn't exist (atomic)
        if not os.path.exists(user_config_path):
            print("User config not found, copying from defaults...")
            os.makedirs(os.path.dirname(user_config_path), exist_ok=True)

            with open(default_config) as f:
                write_file_atomic(user_config_path, f.read())
            print(f"Created {user_config_path}")

        # Ensure node_id exists and matches hardware (add/update if needed, Pi only)
        ensure_node_id(user_config_path)

        # Overlay user config if it exists and has content
        if os.path.exists(user_config_path):
            print(f"Loading user config from {user_config_path}")
            with open(user_config_path) as f:
                user = yaml.safe_load(f)

            if user:  # Only merge if user.yml has actual content
                print("Applying user overrides...")
                migrate_doppler_span(user)
                migrate_tracker_forward(user)
                migrate_remove_tracker(user)
                migrate_adsb_truth_server(user)
                merge(config, user)
            else:
                print("User config is empty, using defaults")

        # Overlay forced config (highest priority)
        if os.path.exists(forced_config):
            print(f"Loading forced config from {forced_config}")
            with open(forced_config) as f:
                forced = yaml.safe_load(f)

            if forced:  # Only merge if content exists
                print("Applying forced overrides...")
                merge(config, forced)

        # Migrate legacy field formats forward (e.g. scalar -> per-tuner gainReduction)
        migrate_gain_reduction(config)

        # Write merged config to output
        print(f"Writing merged config to {output_config_path}")
        os.makedirs(os.path.dirname(output_config_path), exist_ok=True)
        write_file_atomic(output_config_path, yaml.dump(
            config, default_flow_style=False, sort_keys=False))

        # Generate .env file for tar1090-node
        generate_env_file(config, os.path.dirname(output_config_path))

        # Generate config file for the retina-tracker sidecar
        generate_retina_tracker_config(config, os.path.dirname(output_config_path))

        print("Config merge completed successfully!")

    except Exception as e:
        print(f"ERROR during config merge: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()
